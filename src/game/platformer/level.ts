  const spiderX = viewportWidth * 3.55;
  const secondSpiderX = viewportWidth * 7.55;
  const thirdSpiderX = viewportWidth * 12.25;
  const fourthSpiderX = viewportWidth * 17.4;
  const fifthSpiderX = viewportWidth * 22.85;
  const sixthSpiderX = viewportWidth * 27.85;
  const seventhSpiderX = viewportWidth * 32.85;

